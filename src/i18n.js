// ?lang=en в адресе или сам, если среди языков браузера нет русского.

let lang = 'ru';
export const getLang = () => lang;
export const setLang = (l) => { lang = l === 'en' ? 'en' : 'ru'; };

// Язык при первом открытии: параметр адреса важнее сохранённого выбора, тот — важнее языка браузера.
export function initialLang(saved) {
  try {
    const q = new URLSearchParams(location.search).get('lang');
    if (q === 'ru' || q === 'en') return q;
  } catch (e) { /* адрес недоступен — идём дальше */ }
  if (saved === 'ru' || saved === 'en') return saved;
  const prefs = typeof navigator !== 'undefined' && navigator.languages && navigator.languages.length ? navigator.languages : ['ru'];
  return prefs.some((p) => /^ru\b/i.test(p)) ? 'ru' : 'en';
}

// tr('ключ', { имя: значение }) — строка на текущем языке; {имя} в строке заменяется значением.
export function tr(key, vars) {
  const s = (DICT[lang] && DICT[lang][key]) ?? DICT.ru[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}

